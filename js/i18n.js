let current = null;

export function detectLanguage() {
  const stored = localStorage.getItem('shadercreator.lang');
  if (stored && STRINGS[stored]) return stored;
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'de';
  localStorage.setItem('shadercreator.lang', current);
  document.documentElement.lang = current;
}

export function getLanguage() {
  if (!current) setLanguage(detectLanguage());
  return current;
}

export function t(key) {
  if (!current) setLanguage(detectLanguage());
  return STRINGS[current][key] ?? STRINGS.de[key] ?? key;
}
